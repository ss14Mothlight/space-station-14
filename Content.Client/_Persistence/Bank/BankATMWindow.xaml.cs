using Content.Client.UserInterface.Controls;
using Content.Shared._Persistence.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Persistence.Bank;

[GenerateTypedNameReferences]
public sealed partial class BankATMWindow : FancyWindow
{
    public event Action<int>? OnWithdraw;
    public event Action? OnDeposit;

    public BankATMWindow()
    {
        RobustXamlLoader.Load(this);

        WithdrawButton.OnPressed += _ =>
        {
            if (int.TryParse(WithdrawEdit.Text, out var amount) && amount > 0)
                OnWithdraw?.Invoke(amount);
        };
        DepositButton.OnPressed += _ => OnDeposit?.Invoke();
    }

    public void UpdateState(BankATMMenuInterfaceState state)
    {
        BalanceLabel.Text = state.Enabled
            ? SharedBankSystem.ToSpesoString(state.Balance)
            : Loc.GetString("bank-atm-menu-no-bank");
        WithdrawButton.Disabled = !state.Enabled;

        DepositButton.Disabled = !state.Enabled || state.Deposit <= 0;
        DepositLabel.Text = state.Deposit switch
        {
            < 0 => Loc.GetString("bank-atm-menu-cash-error"),
            0 => Loc.GetString("bank-atm-menu-no-deposit"),
            _ => SharedBankSystem.ToSpesoString(state.Deposit),
        };
    }
}
