using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Persistence.GridControl;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Persistence.GridControl;

[GenerateTypedNameReferences]
public sealed partial class BSPAnchorKeyWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = null!;
    [Dependency] private IGameTiming _timing = null!;

    private readonly SharedTransformSystem _transform;

    public EntityUid Owner;

    private BSPAnchorKeyBoundUserInterfaceState? _state;
    private TimeSpan _nextPositionUpdate;

    public BSPAnchorKeyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _transform = _entMan.System<SharedTransformSystem>();
    }

    private static string FormatPosition(Vector2 position)
    {
        return $"({(int) position.X}, {(int) position.Y})";
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state == null)
            return;

        switch (_state.State)
        {
            case BSPState.Parking:
            case BSPState.Unparking:
            {
                var delay = TimeSpan.FromSeconds(_state.State == BSPState.Parking ? _state.ParkDelay : _state.UnparkDelay);
                var remaining = _state.RoutineStartTime.GetValueOrDefault() + delay - _timing.CurTime;
                RoutineTimer.Text = Loc.GetString(_state.State == BSPState.Parking ? "bsp-window-parking-in" : "bsp-window-unparking-in",
                    ("seconds", (int) Math.Max(remaining.TotalSeconds, 0)));
                RoutineProgress.Value = delay > TimeSpan.Zero ? (float) Math.Clamp((delay - remaining) / delay, 0, 1) : 1;
                break;
            }
            case BSPState.Parked:
            {
                if (_timing.RealTime < _nextPositionUpdate || !_entMan.EntityExists(Owner))
                    break;

                _nextPositionUpdate = _timing.RealTime + TimeSpan.FromSeconds(1);
                var position = _transform.GetWorldPosition(Owner);
                var target = _state.ParkWorldPosition.GetValueOrDefault(position);
                var offset = target - position;
                var distance = offset.Length();

                MyCoordinatesLabel.Text = Loc.GetString("bsp-window-my-coordinates", ("coordinates", FormatPosition(position)));
                ParkedCoordinatesLabel.Text = Loc.GetString("bsp-window-parked-coordinates", ("coordinates", FormatPosition(target)));
                DistanceLabel.Text = Loc.GetString("bsp-window-distance", ("distance", (int) distance), ("direction", offset.GetDir().ToString()));

                var inRange = distance <= _state.UnparkMaxDistance;
                DistanceLabel.FontColorOverride = inRange ? Color.LimeGreen : Color.DarkRed;
                InitiateUnparkButton.Disabled = !inRange || !_state.CanAct;
                break;
            }
        }
    }

    public void UpdateState(BSPAnchorKeyBoundUserInterfaceState state)
    {
        _state = state;
        _nextPositionUpdate = TimeSpan.Zero;

        PrivilegedIdButton.Text = state.IdName ?? string.Empty;
        GridSizeLabel.Text = state.OwnerName != null
            ? Loc.GetString("bsp-window-grid-size-limit", ("tiles", state.GridTileCount), ("owned", state.GridOwnerTotalTiles), ("limit", state.TileLimit))
            : Loc.GetString("bsp-window-grid-size", ("tiles", state.GridTileCount));
        GridOwnerLabel.Text = Loc.GetString("bsp-window-grid-owner", ("owner", state.OwnerName ?? Loc.GetString("bsp-window-unclaimed")));
        GridNameLabel.Text = Loc.GetString("bsp-window-grid-name", ("name", state.GridName ?? Loc.GetString("bsp-window-no-grid")));

        string? error = null;
        if (state.GridName == null)
            error = Loc.GetString("bsp-window-no-grid-detected");
        else if (!state.IsAuth)
            error = Loc.GetString("bsp-window-not-authorized");
        else if (state.ErrorMessage != null)
            error = state.ErrorMessage;

        ErrorLabel.Text = error ?? string.Empty;
        ErrorLabel.Visible = error != null;

        IdleContainer.Visible = state.State == BSPState.Idle;
        RoutineContainer.Visible = state.State is BSPState.Parking or BSPState.Unparking;
        ParkedContainer.Visible = state.State == BSPState.Parked;
        ParkedDetails.Visible = state.State is BSPState.Parked or BSPState.Unparking;

        InitiateParkButton.Disabled = !state.CanAct;
        InitiateUnparkButton.Disabled = true; // Enabled once we know we're close enough, see FrameUpdate.
        ClearOwnershipButton.Pressed = state.ClearOwnership;
    }
}
