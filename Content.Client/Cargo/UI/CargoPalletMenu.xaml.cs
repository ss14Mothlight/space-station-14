using Content.Client.UserInterface.Controls;
using Content.Shared._Persistence.Bank;
using Content.Shared._Persistence.Cargo;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Cargo.UI;

[GenerateTypedNameReferences]
public sealed partial class CargoPalletMenu : FancyWindow
{
    public Action? SellRequested;
    public Action? AppraiseRequested;

    // Mothlight begin - payout mode and target faction
    public Action<CargoSaleMode>? ModeSelected;
    public Action<int>? StationSelected;

    private readonly List<int> _stations = new();
    private int _appraisal;
    // Mothlight end

    public CargoPalletMenu()
    {
        RobustXamlLoader.Load(this);
        SellButton.OnPressed += OnSellPressed;
        AppraiseButton.OnPressed += OnAppraisePressed;

        // Mothlight begin
        foreach (var mode in Enum.GetValues<CargoSaleMode>())
        {
            PaymentModeOptions.AddItem(Loc.GetString($"cargo-pallet-mode-{mode.ToString().ToLowerInvariant()}"), (int) mode);
        }

        PaymentModeOptions.OnItemSelected += args =>
        {
            PaymentModeOptions.SelectId(args.Id);
            ModeSelected?.Invoke((CargoSaleMode) args.Id);
        };
        PayToOptions.OnItemSelected += args =>
        {
            PayToOptions.SelectId(args.Id);
            StationSelected?.Invoke(_stations[args.Id]);
        };
        // Mothlight end
    }

    public void SetAppraisal(int amount)
    {
        _appraisal = amount; // Mothlight
        AppraisalLabel.Text = SharedBankSystem.ToSpesoString(amount); // Mothlight - spesos
    }

    public void SetCount(int count)
    {
        CountLabel.Text = count.ToString();
    }
    public void SetEnabled(bool enabled)
    {
        AppraiseButton.Disabled = !enabled;
        SellButton.Disabled = !enabled;
    }

    // Mothlight begin
    public void SetSale(CargoPalletSaleState? sale)
    {
        if (sale == null)
            return;

        PaymentModeOptions.SelectId((int) sale.Mode);
        PayToContainer.Visible = sale.Mode == CargoSaleMode.Deposit;

        _stations.Clear();
        PayToOptions.Clear();
        PayToOptions.AddItem(Loc.GetString("cargo-pallet-menu-own-faction"), _stations.Count);
        _stations.Add(0);
        foreach (var (id, name) in sale.Factions)
        {
            PayToOptions.AddItem(name, _stations.Count);
            _stations.Add(id);
        }

        var selected = _stations.IndexOf(sale.SelectedStation);
        if (selected < 0)
        {
            // Not a faction they're with, but still where the money's going.
            PayToOptions.AddItem(sale.SelectedName ?? Loc.GetString("cargo-pallet-menu-unknown-faction"), _stations.Count);
            selected = _stations.Count;
            _stations.Add(sale.SelectedStation);
        }

        PayToOptions.SelectId(selected);

        TaxLabel.Visible = sale.TaxRate > 0 && sale.TaxingName != null;
        TaxLabel.Text = Loc.GetString("cargo-pallet-menu-tax", ("rate", sale.TaxRate), ("faction", sale.TaxingName ?? string.Empty));

        var tax = (int) Math.Round(_appraisal * sale.TaxRate / 100f);
        PayoutLabel.Text = SharedBankSystem.ToSpesoString(_appraisal - tax);
    }
    // Mothlight end

    private void OnSellPressed(BaseButton.ButtonEventArgs obj)
    {
        SellRequested?.Invoke();
    }

    private void OnAppraisePressed(BaseButton.ButtonEventArgs obj)
    {
        AppraiseRequested?.Invoke();
    }
}
